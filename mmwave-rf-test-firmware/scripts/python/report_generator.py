class ReportGenerator:
    """Generates HTML and JSON test reports."""

    def generate_html(self, report_data: Dict[str, Any], output_path: str):
        """Generate an HTML test report."""
        session = report_data.get("session", {})
        summary = report_data.get("summary", {})
        results = session.get("results", [])

        # Build result rows
        rows = []
        for idx, r in enumerate(results, 1):
            result_class = r.get("result", "").lower()
            row = (
                f"<tr>"
                f"<td>{idx}</td>"
                f"<td>{r.get('test_name', '')}</td>"
                f"<td>{r.get('channel', 0)}</td>"
                f"<td>{r.get('frequency_ghz', 0):.3f}</td>"
                f"<td><strong>{r.get('measured_value', 0):.2f}</strong></td>"
                f"<td>[{r.get('lower_limit', '')}, {r.get('upper_limit', '')}]</td>"
                f"<td>{r.get('unit', '')}</td>"
                f"<td class='{result_class}'>{r.get('result', '')}</td>"
                f"<td>{r.get('duration_ms', 0):.0f}</td>"
                f"</tr>"
            )
            rows.append(row)

        overall = session.get("overall_result", "UNKNOWN")
        overall_class = "overall-pass" if overall == "PASS" else "overall-fail"

        html = HTML_TEMPLATE.format(
            session_id=session.get("session_id", ""),
            device_serial=session.get("device_serial", "N/A"),
            profile_name=session.get("profile_name", ""),
            firmware_version=session.get("firmware_version", ""),
            start_time=session.get("start_time", ""),
            end_time=session.get("end_time", ""),
            overall_result=overall,
            overall_class=overall_class,
            total=summary.get("total", 0),
            passed=summary.get("passed", 0),
            failed=summary.get("failed", 0),
            yield_pct=summary.get("yield_pct", 0.0),
            result_rows="\n            ".join(rows),
            gen_time=datetime.now().isoformat(),
        )

        output = Path(output_path)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(html, encoding="utf-8")
        logger.info(f"HTML report generated: {output_path}")

    def generate_json(self, report_data: Dict[str, Any], output_path: str):
        """Generate a JSON test report for database ingestion."""
        output = Path(output_path)
        output.parent.mkdir(parents=True, exist_ok=True)

        json_data = {
            "report_version": "1.0",
            "generated_at": datetime.now().isoformat(),
            **report_data,
        }

        output.write_text(
            json.dumps(json_data, indent=2, default=str),
            encoding="utf-8",
        )
        logger.info(f"JSON report generated: {output_path}")

    def generate_csv(self, report_data: Dict[str, Any], output_path: str):
        """Generate a CSV summary for spreadsheet analysis."""
        session = report_data.get("session", {})
        results = session.get("results", [])

        output = Path(output_path)
        output.parent.mkdir(parents=True, exist_ok=True)

        lines = [
            "Test Name,Channel,Frequency (GHz),Measured,Lower Limit,"
            "Upper Limit,Unit,Result,Duration (ms)"
        ]
        for r in results:
            line = (
                f"{r.get('test_name','')},{r.get('channel',0)},"
                f"{r.get('frequency_ghz',0):.3f},{r.get('measured_value',0):.3f},"
                f"{r.get('lower_limit','')},{r.get('upper_limit','')},"
                f"{r.get('unit','')},{r.get('result','')},{r.get('duration_ms',0):.0f}"
            )
            lines.append(line)

        output.write_text("\n".join(lines), encoding="utf-8")
        logger.info(f"CSV report generated: {output_path}")
